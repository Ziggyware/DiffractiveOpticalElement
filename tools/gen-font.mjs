const CHARS = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?-+:/*\'()=';
const cols = []; // 5 bytes per char, bit0 = top row
for (const ch of CHARS) {
  const art = ART[ch] || ART[' '];
  if (art.length !== 7) throw new Error('glyph rows ' + ch);
  for (let c = 0; c < 5; c++) {
    let b = 0;
    for (let r = 0; r < 7; r++) {
      const px = art[r][c];
      if (px === undefined) throw new Error('glyph cols ' + ch);
      if (px === '#' || px === 'X') b |= 1 << r;
    }
    cols.push(b);
  }
}
const b64 = Buffer.from(cols).toString('base64');
